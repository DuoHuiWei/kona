/*
 * Rotated MSB comparison backend for Kona/Cong.
 *
 * This is the bit-sliced "Rotated MSB Comparison" idea from
 * Zhang et al., Secure and Practical Time Series Analytics With Mixed Model.
 *
 * IMPORTANT ADAPTATION:
 *   The paper stores the compared value as subtractive shares m = m1 - m0.
 *   Kona's Cong path stores values as additive Z_2^64 shares m = m0 + m1.
 *   Therefore both parties bit-decompose their LOCAL difference
 *
 *       d_b = left_b - right_b,
 *
 *   so d = d_0 + d_1 (mod 2^64).
 *
 *   We then apply exactly the same carry recurrence, with party 1 providing
 *   the "p" operand and party 0 providing the "q" operand.  No comparison
 *   flag is reconstructed.  The final XOR-share is converted to an
 *   arithmetic share through KonaShareConversion::B2A_batch_l2().
 *
 * Security / arithmetic precondition:
 *   As in kona-pcr-compare.hpp, signed-MSB comparison is valid when the true
 *   difference lies in (-2^63, 2^63), i.e. values are represented in the
 *   same bounded 64-bit domain used by the existing comparator path.
 *
 * AND primitive:
 *   This header intentionally reuses
 *   KonaPcrCompare::xor_and_packed_batch_l2().  In the current repository
 *   that primitive is protocol-shaped and correctness-oriented; replace its
 *   zero-triple internals with real preprocessed Boolean triples if/when the
 *   rest of the benchmark is upgraded to production MPC.
 */

namespace KonaRotatedMsbCompare
{

static const int RMSB_K = 64;
using Share64 = Z2<RMSB_K>;

inline uint64_t z2_to_u64(const Share64& x)
{
    return static_cast<uint64_t>(x.get_limb(0));
}

inline Share64 u64_to_z2(uint64_t x)
{
    return Share64(static_cast<mp_limb_t>(x));
}

inline uint64_t active_mask(std::size_t n, std::size_t chunk)
{
    const std::size_t begin = chunk * 64;
    if (begin >= n)
        return 0;
    const std::size_t remain = n - begin;
    if (remain >= 64)
        return ~uint64_t(0);
    return (uint64_t(1) << remain) - 1;
}

inline void xor_not_in_place(std::vector<uint64_t>& x,
                             std::size_t logical_size,
                             int player_no)
{
    // XOR sharing: flipping exactly one party's share negates the secret bit.
    // The paper flips S1, so keep the same convention.
    if (player_no != 1)
        return;

    for (std::size_t c = 0; c < x.size(); ++c)
        x[c] ^= active_mask(logical_size, c);
}

inline std::vector<uint64_t>
and_packed(const std::vector<uint64_t>& x,
           const std::vector<uint64_t>& y,
           RealTwoPartyPlayer* player)
{
    if (x.size() != y.size())
        throw std::runtime_error("rotated-msb: packed AND size mismatch");

    return KonaPcrCompare::xor_and_packed_batch_l2(x, y, player);
}

/*
 * Return XOR shares of [x < y] for all input pairs.
 *
 * The algorithm is bit-sliced: one secure AND call processes up to 64
 * independent comparisons per machine word, so a Cong network layer can be
 * handled as one rotated comparison batch rather than comparator-by-comparator.
 */
inline std::vector<uint64_t>
rotated_msb_lt_boolean_packed_l2(const std::vector<Share64>& x,
                                 const std::vector<Share64>& y,
                                 RealTwoPartyPlayer* player)
{
    if (!player)
        throw std::runtime_error("rotated-msb: null player");
    if (x.size() != y.size())
        throw std::runtime_error("rotated-msb: input size mismatch");

    const std::size_t n = x.size();
    const std::size_t chunks = (n + 63) / 64;
    if (n == 0)
        return {};

    // M[row][chunk], row 0 = MSB (bit 63), row 63 = LSB (bit 0).
    std::vector<std::vector<uint64_t> > M(
        RMSB_K, std::vector<uint64_t>(chunks, 0));

    for (std::size_t i = 0; i < n; ++i)
    {
        const uint64_t d =
            z2_to_u64(x[i] - y[i]); // local additive-share difference
        const std::size_t c = i / 64;
        const unsigned lane = static_cast<unsigned>(i % 64);

        for (int row = 0; row < RMSB_K; ++row)
        {
            const unsigned bit = static_cast<unsigned>(63 - row);
            if ((d >> bit) & uint64_t(1))
                M[row][c] |= (uint64_t(1) << lane);
        }
    }

    const int me = player->my_num();
    std::vector<uint64_t> zeros(chunks, 0);
    std::vector<uint64_t> p = (me == 1 ? M[63] : zeros);
    std::vector<uint64_t> q = (me == 0 ? M[63] : zeros);

    // Carry generated by the LSB.
    std::vector<uint64_t> carry = and_packed(p, q, player);

    // Algorithm 2 processes bits l-1 down to 2, i.e. rows 62 down to 1.
    // Recurrence:
    //   o = NOT(p AND q)
    //   h = NOT(M_j AND carry)
    //   carry = NOT(h AND o)
    // which equals the carry of p + q into the next more significant bit.
    for (int row = 62; row >= 1; --row)
    {
        p = (me == 1 ? M[row] : zeros);
        q = (me == 0 ? M[row] : zeros);

        std::vector<uint64_t> o = and_packed(p, q, player);
        xor_not_in_place(o, n, me);

        std::vector<uint64_t> h = and_packed(M[row], carry, player);
        xor_not_in_place(h, n, me);

        carry = and_packed(h, o, player);
        xor_not_in_place(carry, n, me);
    }

    // Signed comparison bit = carry into MSB XOR local MSB share.
    for (std::size_t c = 0; c < chunks; ++c)
    {
        carry[c] ^= M[0][c];
        carry[c] &= active_mask(n, c);
    }

    return carry;
}

inline std::vector<Share64>
unpack_boolean_shares(const std::vector<uint64_t>& packed,
                      std::size_t n)
{
    std::vector<Share64> out(n);
    for (std::size_t i = 0; i < n; ++i)
    {
        const uint64_t bit =
            (packed[i / 64] >> static_cast<unsigned>(i % 64)) & 1;
        out[i] = u64_to_z2(bit);
    }
    return out;
}

inline std::vector<Share64>
rotated_msb_compare_lt_batch_l2(const std::vector<Share64>& x,
                                const std::vector<Share64>& y,
                                RealTwoPartyPlayer* player)
{
    const std::vector<uint64_t> packed =
        rotated_msb_lt_boolean_packed_l2(x, y, player);
    std::vector<Share64> bool_shares =
        unpack_boolean_shares(packed, x.size());

    // Keep the exact representation expected by the existing Cong swap path.
    return KonaShareConversion::B2A_batch_l2<RMSB_K>(bool_shares, player);
}

inline std::vector<Share64>
rotated_msb_compare_gt_batch_l2(const std::vector<Share64>& x,
                                const std::vector<Share64>& y,
                                RealTwoPartyPlayer* player)
{
    // x > y  <=>  y < x
    return rotated_msb_compare_lt_batch_l2(y, x, player);
}

inline void rotated_msb_compare_in_vec_l2(
    const std::vector<std::array<Share64, 2> >& shares,
    const std::vector<int>& compare_idx_vec,
    std::vector<Share64>& compare_res,
    bool greater_than,
    RealTwoPartyPlayer* player)
{
    if (compare_idx_vec.size() % 2 != 0)
        throw std::runtime_error(
            "rotated-msb: compare_idx_vec must contain index pairs");

    const std::size_t pairs = compare_idx_vec.size() / 2;
    std::vector<Share64> left(pairs), right(pairs);

    for (std::size_t i = 0; i < pairs; ++i)
    {
        const int li = compare_idx_vec[2 * i];
        const int ri = compare_idx_vec[2 * i + 1];
        if (li < 0 || ri < 0 ||
            static_cast<std::size_t>(li) >= shares.size() ||
            static_cast<std::size_t>(ri) >= shares.size())
            throw std::runtime_error(
                "rotated-msb: comparator wire index out of range");

        // Pair[0] is the sortable key (distance); Pair[1] is payload/label.
        left[i] = shares[static_cast<std::size_t>(li)][0];
        right[i] = shares[static_cast<std::size_t>(ri)][0];
    }

    const std::vector<Share64> bits = greater_than ?
        rotated_msb_compare_gt_batch_l2(left, right, player) :
        rotated_msb_compare_lt_batch_l2(left, right, player);

    // Match ss_vec_kona_l2(): duplicate each pair's arithmetic flag for the
    // two flattened wire indices, exactly as the existing PCR backend does.
    compare_res.resize(compare_idx_vec.size());
    for (std::size_t i = 0; i < pairs; ++i)
    {
        compare_res[2 * i] = bits[i];
        compare_res[2 * i + 1] = bits[i];
    }
}

} // namespace KonaRotatedMsbCompare

#endif
